//! Phase 15E: static shell translation contract (13 exact upstream IDs).
//! Full upstream UI catalog migration and native translation quality remain separate gates.
//! Render strings as plain text only; no HTML, interpolation or file lookup.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
#[repr(usize)]
pub enum UiLanguage {
    En,
    De,
    Es,
    Fr,
    PtBr,
    PtPt,
    Ru,
    Tr,
    Vi,
    Ja,
    Ko,
    ZhCn,
    ZhTw,
}

impl UiLanguage {
    pub const ALL: [Self; 13] = [
        Self::En,
        Self::De,
        Self::Es,
        Self::Fr,
        Self::PtBr,
        Self::PtPt,
        Self::Ru,
        Self::Tr,
        Self::Vi,
        Self::Ja,
        Self::Ko,
        Self::ZhCn,
        Self::ZhTw,
    ];

    pub fn parse(tag: &str) -> Option<Self> {
        match tag {
            "en" => Some(Self::En),
            "de" => Some(Self::De),
            "es" => Some(Self::Es),
            "fr" => Some(Self::Fr),
            "pt-BR" => Some(Self::PtBr),
            "pt-PT" => Some(Self::PtPt),
            "ru" => Some(Self::Ru),
            "tr" => Some(Self::Tr),
            "vi" => Some(Self::Vi),
            "ja" => Some(Self::Ja),
            "ko" => Some(Self::Ko),
            "zh-CN" => Some(Self::ZhCn),
            "zh-TW" => Some(Self::ZhTw),
            _ => None,
        }
    }

    /// Unknown, malformed or unset locale selects predictable English.
    pub fn select(value: Option<&str>) -> Self {
        value.and_then(Self::parse).unwrap_or(Self::En)
    }

    pub const fn tag(self) -> &'static str {
        match self {
            Self::En => "en",
            Self::De => "de",
            Self::Es => "es",
            Self::Fr => "fr",
            Self::PtBr => "pt-BR",
            Self::PtPt => "pt-PT",
            Self::Ru => "ru",
            Self::Tr => "tr",
            Self::Vi => "vi",
            Self::Ja => "ja",
            Self::Ko => "ko",
            Self::ZhCn => "zh-CN",
            Self::ZhTw => "zh-TW",
        }
    }
}

